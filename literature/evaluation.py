"""Compare enrichment output with independently written expected answers.

Modeled on the general idea of the JMIR infodemiology study (LLM output
compared with human judgments): the expected labels are written by hand from
the article text, never generated by the model being evaluated. Results on
the synthetic set measure the pipeline on invented cases; they are not
evidence of real-world accuracy.
"""

import json
from pathlib import Path

import pandas as pd

from literature.discovery import ELIGIBLE


def first_part(value):
    return str(value).split(",")[0].strip().casefold() if value else ""


def location_facts(facts, sample_id, approvable_only):
    return [fact for fact in facts if fact["Sample_ID"] == sample_id and fact["Field"] == "Location"
            and (fact["Approvable"] or not approvable_only)]


def naive_acceptance(fact):
    """What a pipeline without verification would accept: any model 'collection site' claim."""

    return (fact["Field"] in {"Location", "Coordinates"} and fact["Location_Role"] == "Sample collection site"
            and fact["Evidence_Type"] in {"Directly stated", "Sample-to-site table"} and fact["Sample_ID"] != "STUDY")


def score_fact(fact, gold):
    """True/False when the gold labels say what this approvable fact should be; None if not scored."""

    field, value = fact["Field"], str(fact["Value"])
    if field == "Location":
        return gold["Expected_Location_Outcome"] == "approvable" and first_part(value) == first_part(
            gold["Expected_Location"])
    if field == "Site_Identifier":
        return gold["Expected_Site"] is not None and first_part(value) == first_part(gold["Expected_Site"])
    if field == "Collection_Date":
        return value == gold["Expected_Date"]
    if field == "Collection_Date_Range":
        return value == gold["Expected_Date_Range"]
    if field == "Coordinates":
        expected = gold["Expected_Coordinates"]
        numbers = [float(part) for part in value.replace(" ", "").split(",")]
        return expected is not None and all(abs(a - b) < 1e-6 for a, b in zip(numbers, expected))
    return None


def evaluate(session, labels_path):
    """Metrics dictionary plus a per-sample table."""

    labels = json.loads(Path(labels_path).read_text(encoding="utf-8"))
    gold = {item["Sample_ID"]: item for item in labels["samples"]}
    publications = session["publications"]
    facts = session["facts"]
    rows = []
    for sample_id, expected in gold.items():
        found = publications[(publications["Sample_ID"] == sample_id)
                             & publications["Relationship_Type"].isin(ELIGIBLE)
                             & publications["Eligible_For_Enrichment"]]
        articles = sorted(found["Article_ID"])
        raw = location_facts(facts, sample_id, approvable_only=False)
        approvable = location_facts(facts, sample_id, approvable_only=True)
        outcome = expected["Expected_Location_Outcome"]
        rows.append({
            "Sample_ID": sample_id, "Scenario": expected["Scenario"],
            "Article_Association_Correct": articles == sorted(expected["Expected_Articles"]),
            "Location_Extracted": (any(first_part(fact["Value"]) == first_part(expected["Expected_Location"])
                                       for fact in raw) if expected["Expected_Location"] else None),
            "Approvable_Locations": "; ".join(fact["Value"] for fact in approvable),
            "Correct_Sample_Location": (any(score_fact(fact, expected) for fact in approvable)
                                        if outcome == "approvable" else None),
            "Incorrect_Assignment": any(not score_fact(fact, expected) for fact in approvable),
            "Naive_Incorrect_Assignment": any(
                naive_acceptance(fact) and fact["Field"] == "Location" and not score_fact(fact, expected)
                for fact in raw),
            "Abstained": (not approvable) if outcome in {"abstain", "contradiction"} else None,
            "Contradiction_Flagged": (any(fact["Evidence_Status"] == "Contradictory" for fact in raw)
                                      if outcome == "contradiction" else None),
        })
    table = pd.DataFrame(rows)
    approvable_all = [fact for fact in facts if fact["Approvable"] and fact["Sample_ID"] in gold]
    scores = [score_fact(fact, gold[fact["Sample_ID"]]) for fact in approvable_all]
    scored = [score for score in scores if score is not None]
    negatives = table[table["Abstained"].notna()]
    expected_locations = table[table["Location_Extracted"].notna()]
    expected_approvable = table[table["Correct_Sample_Location"].notna()]

    def share(numerator, denominator):
        return f"{numerator}/{denominator}" + (f" ({numerator / denominator:.0%})" if denominator else "")

    metrics = {
        "Dataset version": labels["dataset_version"],
        "Correct article associations": share(int(table["Article_Association_Correct"].sum()), len(table)),
        "Correct location extraction (model output, before checks)": share(
            int(expected_locations["Location_Extracted"].sum()), len(expected_locations)),
        "Correct sample-to-location associations (approvable)": share(
            int(expected_approvable["Correct_Sample_Location"].sum()), len(expected_approvable)),
        "Samples with an incorrect approvable location": int(table["Incorrect_Assignment"].sum()),
        "Samples with an incorrect location if model claims were accepted unchecked": int(table["Naive_Incorrect_Assignment"].sum()),
        "Precision of approvable proposals (scored fields)": share(sum(scored), len(scored)),
        "False-positive rate (samples that should abstain or be flagged)": share(
            int((~negatives["Abstained"].astype(bool)).sum()), len(negatives)),
        "Abstention on ambiguous or insufficient examples": share(
            int(negatives["Abstained"].astype(bool).sum()), len(negatives)),
        "Contradictions flagged": share(int(table["Contradiction_Flagged"].dropna().astype(bool).sum()),
                                        int(table["Contradiction_Flagged"].notna().sum())),
        "Human reviewer agreement": "Not available (no independent reviewer labels were recorded)",
    }
    return metrics, table
